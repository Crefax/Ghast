package ghast.oracle.setup;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Writes the Yarn coverage report for the movement-relevant classes from a tiny v2 file with the
 * namespaces {@code official intermediary named}. Only intermediary and named (Yarn) names are printed.
 *
 * <p>Usage: {@code Coverage <mappings.tiny> <out.md> <mappings label> <class.list>}
 */
public final class Coverage {
    private static final Pattern UNNAMED = Pattern.compile("^(field|method|comp|class)_\\d+$");
    private static final Pattern OBJ = Pattern.compile("L([^;]+);");

    record Member(char kind, String descOfficial, String inter, String named) {}

    static final class Cls {
        String inter;
        String named;
        final List<Member> members = new ArrayList<>();
    }

    public static void main(String[] args) throws IOException {
        if (args.length != 6) {
            System.err.println("usage: Coverage <mappings.tiny> <out.md> <mappings label> <class.list> <mc version> <vendor>");
            System.exit(2);
        }
        Map<String, Cls> byOfficial = new LinkedHashMap<>();
        Map<String, Cls> byNamed = new HashMap<>();
        Cls cur = null;
        for (String line : Files.readAllLines(Path.of(args[0]), StandardCharsets.UTF_8)) {
            if (line.startsWith("tiny\t")) {
                if (!line.equals("tiny\t2\t0\tofficial\tintermediary\tnamed")) {
                    throw new IllegalStateException("unexpected header: " + line);
                }
                continue;
            }
            String[] p = line.split("\t", -1);
            if (p[0].equals("c")) {
                cur = new Cls();
                cur.inter = p[2];
                cur.named = p.length > 3 && !p[3].isEmpty() ? p[3] : p[2];
                byOfficial.put(p[1], cur);
                byNamed.put(cur.named, cur);
            } else if (p.length >= 6 && p[0].isEmpty() && (p[1].equals("f") || p[1].equals("m")) && cur != null) {
                String named = p[5].isEmpty() ? p[4] : p[5];
                cur.members.add(new Member(p[1].charAt(0), p[2], p[4], named));
            }
        }
        Map<String, String> officialToNamed = new HashMap<>();
        byOfficial.forEach((o, c) -> officialToNamed.put(o, c.named));

        List<String> wanted = new ArrayList<>();
        Map<String, String> notes = new LinkedHashMap<>();
        String section = "";
        Map<String, String> sectionOf = new HashMap<>();
        for (String line : Files.readAllLines(Path.of(args[3]), StandardCharsets.UTF_8)) {
            line = line.strip();
            if (line.isEmpty() || line.startsWith("#")) {
                continue;
            }
            if (line.startsWith("[") && line.endsWith("]")) {
                section = line.substring(1, line.length() - 1);
                continue;
            }
            if (line.startsWith("note ")) {
                String[] kv = line.substring(5).split("\\s*=\\s*", 2);
                notes.put(kv[0], kv[1]);
                continue;
            }
            wanted.add(line);
            sectionOf.put(line, section);
        }

        StringBuilder md = new StringBuilder();
        md.append("# Yarn coverage of the ").append(args[4]).append(" movement code\n\n");
        md.append("Generated by `").append(args[4].equals("1.8.9") ? "" : "MC=" + args[4] + " ")
                .append("oracle/run.sh coverage` from ").append(args[2]).append(" (").append(args[5]).append(", CC0).\n");
        md.append("Only intermediary (`class_N`, `field_N`, `method_N`) and Yarn names appear here.\n");
        md.append("A member counts as *unnamed* when Yarn has no name for it (it keeps its intermediary name);\n");
        md.append("code in this repository then uses the intermediary name as-is.\n\n");

        md.append("## Summary\n\n| Class (Yarn) | Intermediary | Fields named | Methods named | Unnamed members |\n");
        md.append("|---|---|---|---|---|\n");
        int[] total = new int[4];
        for (String name : wanted) {
            Cls c = byNamed.get(name);
            if (c == null) {
                md.append("| `").append(name).append("` | (not in mappings) | | | |\n");
                continue;
            }
            int f = 0, fn = 0, m = 0, mn = 0;
            for (Member mem : c.members) {
                boolean named = !UNNAMED.matcher(mem.named).matches();
                if (mem.kind == 'f') {
                    f++;
                    fn += named ? 1 : 0;
                } else if (!mem.inter.equals("<init>")) {
                    m++;
                    mn += named ? 1 : 0;
                }
            }
            total[0] += fn;
            total[1] += f;
            total[2] += mn;
            total[3] += m;
            md.append("| `").append(simple(name)).append("` | `").append(simple(c.inter)).append("` | ")
                    .append(fn).append('/').append(f).append(" | ").append(mn).append('/').append(m).append(" | ")
                    .append((f - fn) + (m - mn)).append(" |\n");
        }
        md.append("| **total** | | ").append(total[0]).append('/').append(total[1]).append(" | ")
                .append(total[2]).append('/').append(total[3]).append(" | ")
                .append((total[1] - total[0]) + (total[3] - total[2])).append(" |\n\n");

        if (!notes.isEmpty()) {
            md.append("## Names to read carefully\n\n");
            md.append("Yarn names that are misleading for movement code, and the unnamed members that matter.\n\n");
            md.append("| Member | Meaning |\n|---|---|\n");
            notes.forEach((k, v) -> md.append("| `").append(k).append("` | ").append(v).append(" |\n"));
            md.append('\n');
        }

        md.append("## Per class\n\n");
        String lastSection = null;
        for (String name : wanted) {
            Cls c = byNamed.get(name);
            if (c == null) {
                continue;
            }
            String sec = sectionOf.get(name);
            if (!sec.equals(lastSection)) {
                md.append("### ").append(sec).append("\n\n");
                lastSection = sec;
            }
            md.append("#### `").append(name).append("` (`").append(c.inter).append("`)\n\n");
            List<String> unnamed = new ArrayList<>();
            List<String> named = new ArrayList<>();
            for (Member mem : c.members) {
                if (mem.inter.equals("<init>")) {
                    continue;
                }
                String desc = remapDesc(mem.descOfficial, officialToNamed);
                String row = (mem.kind == 'f' ? "field " : "method ") + "`" + mem.named + "` "
                        + (mem.kind == 'f' ? "`" + desc + "`" : "`" + desc + "`")
                        + (mem.named.equals(mem.inter) ? "" : " ← `" + mem.inter + "`");
                if (UNNAMED.matcher(mem.named).matches()) {
                    unnamed.add(row);
                } else {
                    named.add(row);
                }
            }
            if (unnamed.isEmpty()) {
                md.append("All ").append(named.size()).append(" members named.\n\n");
            } else {
                md.append("Unnamed (").append(unnamed.size()).append("):\n\n");
                for (String u : unnamed) {
                    md.append("- ").append(u).append('\n');
                }
                md.append('\n');
            }
            md.append("<details><summary>Named (").append(named.size()).append(")</summary>\n\n");
            for (String n : named) {
                md.append("- ").append(n).append('\n');
            }
            md.append("\n</details>\n\n");
        }
        Path out = Path.of(args[1]);
        Path tmp = out.resolveSibling("." + out.getFileName() + ".partial");
        Files.writeString(tmp, md.toString(), StandardCharsets.UTF_8);
        Files.move(tmp, out, java.nio.file.StandardCopyOption.REPLACE_EXISTING, java.nio.file.StandardCopyOption.ATOMIC_MOVE);
        System.out.println("[coverage] wrote " + args[1]);
    }

    private static String simple(String internal) {
        return internal.substring(internal.lastIndexOf('/') + 1);
    }

    /** Rewrites official class names in a descriptor to Yarn simple names (for readability). */
    private static String remapDesc(String desc, Map<String, String> officialToNamed) {
        Matcher m = OBJ.matcher(desc);
        StringBuilder sb = new StringBuilder();
        while (m.find()) {
            String n = officialToNamed.getOrDefault(m.group(1), m.group(1));
            m.appendReplacement(sb, Matcher.quoteReplacement("L" + simple(n) + ";"));
        }
        m.appendTail(sb);
        return sb.toString();
    }
}
