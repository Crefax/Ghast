//! `ghast-codegen-data`: regenerates `crates/ghast-data/src/generated/` from the pinned
//! PrismarineJS minecraft-data release.
//!
//! ```text
//! cargo run -p ghast-codegen-data            # fetch (if needed) + write files
//! cargo run -p ghast-codegen-data -- --check # fail if the committed files are stale
//! options: --offline (never download), --cache <dir> (default <repo>/.cache/minecraft-data)
//! ```

#![forbid(unsafe_code)]

mod emit;
mod facts;
mod fetch;
mod generate;
mod model;
mod v1_12;
mod v26_1;

use std::path::{Path, PathBuf};
use std::process::ExitCode;

fn main() -> ExitCode {
    match run() {
        Ok(code) => code,
        Err(e) => {
            eprintln!("error: {e}");
            ExitCode::FAILURE
        }
    }
}

fn run() -> Result<ExitCode, String> {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let root = root
        .canonicalize()
        .map_err(|e| format!("{}: {e}", root.display()))?;
    let mut check = false;
    let mut offline = false;
    let mut cache = root.join(".cache/minecraft-data");
    let mut args = std::env::args().skip(1);
    while let Some(a) = args.next() {
        match a.as_str() {
            "--check" => check = true,
            "--offline" => offline = true,
            "--cache" => cache = PathBuf::from(args.next().ok_or("--cache needs a value")?),
            _ => return Err(format!("unknown argument {a}")),
        }
    }
    let data = fetch::ensure(&cache, offline)?;
    let mut notes = Vec::new();
    let mut files = Vec::new();
    files.extend(generate::v1_8(
        &model::Paths::new(&data, "1.8")?,
        &root.join(facts::V1_8_ORACLE_BOXES),
        &root.join(facts::V1_8_ORACLE_SELECTION),
        &root.join(facts::V1_8_ORACLE_RECIPES),
        &root.join(facts::V1_8_ORACLE_ENTITIES),
        &mut notes,
    )?);
    files.extend(v1_12::generate(
        &model::Paths::new(&data, "1.12.2")?,
        &root.join(facts::V1_12_ORACLE_BOXES),
        &root.join(facts::V1_12_ORACLE_SELECTION),
        &root.join(facts::V1_12_ORACLE_ENTITIES),
        &root.join(facts::V1_12_ORACLE_FACES),
        &mut notes,
    )?);
    files.extend(generate::v1_16_5(
        &model::Paths::new(&data, "1.16.5")?,
        &root.join(facts::V1_16_5_ORACLE_SHAPES),
        &root.join(facts::V1_16_5_ORACLE_VOXELS),
        &root.join(facts::V1_16_5_ORACLE_ENTITIES),
        &mut notes,
    )?);
    files.extend(v26_1::generate(
        &model::Paths::new(&data, "26.1")?,
        &root.join(v26_1::ORACLE_VOXELS),
        &mut notes,
    )?);
    files.push((
        "mod.rs".into(),
        "//! Generated tables, one module per version.\n//!\n//! @generated by `cargo run -p ghast-codegen-data` — do not edit.\n\n#[cfg(feature = \"v1_12\")]\npub(crate) mod v1_12;\n#[cfg(feature = \"v1_16_5\")]\npub(crate) mod v1_16_5;\n#[cfg(feature = \"v1_8\")]\npub(crate) mod v1_8;\n#[cfg(feature = \"v26_1\")]\npub(crate) mod v26_1;\n"
            .into(),
    ));

    let out_dir = root.join("crates/ghast-data/src/generated");
    let mut stale = Vec::new();
    let mut total = 0usize;
    for (rel, contents) in &files {
        let path = out_dir.join(rel);
        total += contents.len();
        let current = std::fs::read_to_string(&path).ok();
        if current.as_deref() == Some(contents.as_str()) {
            continue;
        }
        if check {
            stale.push(rel.clone());
        } else {
            std::fs::create_dir_all(path.parent().ok_or("no parent")?)
                .map_err(|e| e.to_string())?;
            std::fs::write(&path, contents).map_err(|e| format!("{}: {e}", path.display()))?;
            println!("wrote {rel} ({} bytes)", contents.len());
        }
    }
    for n in &notes {
        println!("note: {n}");
    }
    println!("{} files, {total} bytes of generated Rust", files.len());
    if !stale.is_empty() {
        eprintln!(
            "stale generated files (run `cargo run -p ghast-codegen-data`): {}",
            stale.join(", ")
        );
        return Ok(ExitCode::FAILURE);
    }
    Ok(ExitCode::SUCCESS)
}
