//! Cross-check of packet ids against the vanilla server's own report.
//!
//! `java -DbundlerMainClass=net.minecraft.data.Main -jar server.jar --reports` writes
//! `reports/packets.json`: per state and direction, every packet's resource name and
//! protocol id. This module pairs those with minecraft-data's packet names by id and
//! writes a plain table (state, direction, id, vanilla name, minecraft-data name) that is
//! committed and checked by `crates/ghast-protocol/tests/packets_report.rs`. The report
//! itself (a Mojang file) is never committed.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::Path;

use serde_json::Value;

/// `(minecraft-data state, vanilla report state)`.
const STATES: &[(&str, &str)] = &[
    ("handshaking", "handshake"),
    ("status", "status"),
    ("login", "login"),
    ("configuration", "configuration"),
    ("play", "play"),
];
const DIRECTIONS: &[(&str, &str)] = &[("toClient", "clientbound"), ("toServer", "serverbound")];

pub fn write_table(proto: &Value, report: &Value, out: &Path) {
    let mut s = String::from(
        "# Packet ids of protocol 775 (Minecraft 26.1 - 26.1.2) per state and direction:\n\
         # the vanilla resource name (from the 26.1.2 server's `--reports` packets.json)\n\
         # paired by id with the minecraft-data 3.119.0 name the generated code uses.\n\
         # Generated by `cargo run -p ghast-codegen-protocol -- packets-report ...`.\n\
         # state\tdirection\tid\tvanilla\tminecraft-data\n",
    );
    let mut problems = Vec::new();
    for (st, rst) in STATES {
        for (dir, rdir) in DIRECTIONS {
            let ours: BTreeMap<i64, String> = proto[*st][*dir]["types"]["packet"][1][0]["type"][1]
                ["mappings"]
                .as_object()
                .map(|m| {
                    m.iter()
                        // The pre-Netty legacy ping is not a packet of the state machine.
                        .filter(|(_, v)| v.as_str() != Some("legacy_server_list_ping"))
                        .map(|(k, v)| {
                            (
                                crate::ir::parse_int(k).expect("id"),
                                v.as_str().unwrap().to_string(),
                            )
                        })
                        .collect()
                })
                .unwrap_or_default();
            let theirs: BTreeMap<i64, String> = report[*rst][*rdir]
                .as_object()
                .map(|m| {
                    m.iter()
                        .map(|(k, v)| (v["protocol_id"].as_i64().expect("protocol_id"), k.clone()))
                        .collect()
                })
                .unwrap_or_default();
            let ids: std::collections::BTreeSet<i64> =
                ours.keys().chain(theirs.keys()).copied().collect();
            for id in ids {
                let a = theirs.get(&id).map_or("-", String::as_str);
                let b = ours.get(&id).map_or("-", String::as_str);
                if a == "-" || b == "-" {
                    problems.push(format!(
                        "{st} {rdir} {id:#04x}: vanilla {a}, minecraft-data {b}"
                    ));
                }
                let _ = writeln!(s, "{st}\t{rdir}\t{id}\t{a}\t{b}");
            }
        }
    }
    std::fs::write(out, s).expect("write table");
    for p in &problems {
        println!("MISMATCH {p}");
    }
    println!("wrote {} ({} id mismatches)", out.display(), problems.len());
}
