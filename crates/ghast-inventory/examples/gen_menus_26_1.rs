//! Generates `src/generated/menus_26_1.rs`: per item the facts the 26.1 menus' slot rules read
//! (fuel, brewing ingredient / fuel, beacon payment, loom dyes and patterns, banners, whether it
//! fits inside container items, its crafting remainder), from the `item` lines of the oracle's
//! click vectors (`tests/golden/26.1/clicks_seed1.jsonl.gz`, written by the real 26.1 client
//! code after the configuration phase: the vanilla data pack's tags).
//!
//! ```text
//! cargo run -p ghast-inventory --example gen_menus_26_1 -- tests/golden/26.1/clicks_seed1.jsonl.gz
//! ```

use std::fmt::Write as _;
use std::io::Read;

use serde_json::Value;

const FLAGS: &[(&str, &str)] = &[
    ("fuel", "FUEL"),
    ("brewing_ingredient", "BREWING_INGREDIENT"),
    ("brewing_fuel", "BREWING_FUEL"),
    ("beacon_payment", "BEACON_PAYMENT"),
    ("loom_dye_tag", "LOOM_DYE_TAG"),
    ("loom_pattern_tag", "LOOM_PATTERN_TAG"),
    ("banner", "BANNER"),
    ("fits_container", "FITS_CONTAINER"),
    ("has_dye", "HAS_DYE"),
    ("has_patterns", "HAS_PATTERNS"),
];

fn unhex(s: &str) -> Vec<u8> {
    (0..s.len())
        .step_by(2)
        .map(|i| u8::from_str_radix(&s[i..i + 2], 16).unwrap())
        .collect()
}

fn varint(b: &[u8], pos: &mut usize) -> i32 {
    let mut v = 0u32;
    for k in 0..5 {
        let x = b[*pos];
        *pos += 1;
        v |= u32::from(x & 0x7f) << (7 * k);
        if x & 0x80 == 0 {
            break;
        }
    }
    v as i32
}

fn main() {
    let path = std::env::args()
        .nth(1)
        .unwrap_or_else(|| "tests/golden/26.1/clicks_seed1.jsonl.gz".into());
    let mut text = String::new();
    flate2::read::GzDecoder::new(std::fs::File::open(&path).unwrap())
        .read_to_string(&mut text)
        .unwrap();
    let mut flags: Vec<u16> = Vec::new();
    let mut remainders: Vec<(i32, i32, i32)> = Vec::new();
    for line in text.lines() {
        let v: Value = serde_json::from_str(line).unwrap();
        if v["type"] != "item" {
            continue;
        }
        let id = v["id"].as_i64().unwrap() as usize;
        assert_eq!(id, flags.len(), "item ids not dense");
        let mut f = 0u16;
        for (bit, (key, _)) in FLAGS.iter().enumerate() {
            if v[key].as_bool().unwrap_or(false) {
                f |= 1 << bit;
            }
        }
        flags.push(f);
        if let Some(r) = v["remainder"].as_str()
            && r != "00"
        {
            let b = unhex(r);
            let mut pos = 0;
            let count = varint(&b, &mut pos);
            let item = varint(&b, &mut pos);
            let added = varint(&b, &mut pos);
            let removed = varint(&b, &mut pos);
            assert!(
                added == 0 && removed == 0,
                "remainder with components: {line}"
            );
            remainders.push((id as i32, item, count));
        }
    }
    let mut out = String::new();
    writeln!(
        out,
        "// @generated by `cargo run -p ghast-inventory --example gen_menus_26_1` from the item\n\
         // lines of the oracle's 26.1 click vectors (the real client's slot rules after the\n\
         // configuration phase). Do not edit.\n"
    )
    .unwrap();
    for (bit, (key, name)) in FLAGS.iter().enumerate() {
        writeln!(
            out,
            "/// Item fact `{key}`.\npub const {name}: u16 = 1 << {bit};"
        )
        .unwrap();
    }
    writeln!(
        out,
        "\n/// Facts per item registry id.\npub(crate) static MENU_FACTS: [u16; {}] = [",
        flags.len()
    )
    .unwrap();
    for chunk in flags.chunks(16) {
        let row: Vec<String> = chunk.iter().map(|f| format!("{f}")).collect();
        writeln!(out, "    {},", row.join(", ")).unwrap();
    }
    writeln!(out, "];\n").unwrap();
    writeln!(
        out,
        "/// `Item.getCraftingRemainder()`: (item, remainder item, count), sorted by item.\n\
         pub(crate) static REMAINDERS: [(i32, i32, i32); {}] = [",
        remainders.len()
    )
    .unwrap();
    for (a, b, c) in &remainders {
        writeln!(out, "    ({a}, {b}, {c}),").unwrap();
    }
    writeln!(out, "];").unwrap();
    std::fs::write(format!("src/generated/menus_{}.rs", ver_of(&path)), out).unwrap();
    eprintln!(
        "wrote src/generated/menus_{}.rs: {} items, {} remainders",
        ver_of(&path),
        flags.len(),
        remainders.len()
    );
}

/// `26_2` for an input under `tests/golden/26.2/`, else `26_1` (the output file's suffix).
fn ver_of(path: &str) -> &'static str {
    if path.contains("26.2") {
        "26_2"
    } else {
        "26_1"
    }
}
