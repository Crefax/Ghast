//! Generates `src/generated/items_26_1.rs` from Mojang's 26.1.2 data reports
//! (`java -DbundlerMainClass=net.minecraft.data.Main -jar server.jar --reports`): item registry
//! ids, each item's default components that click prediction and the item accessors read,
//! the data component type ids, the menu and potion registries.
//!
//! ```text
//! cargo run -p ghast-inventory --example gen_items_26_1 -- .cache/mojang/26.1.2/reports/reports
//! ```

use std::fmt::Write as _;
use std::path::Path;

use serde_json::Value;

fn registry(r: &Value, name: &str) -> Vec<String> {
    let mut v: Vec<(u64, String)> = r[name]["entries"]
        .as_object()
        .unwrap()
        .iter()
        .map(|(k, e)| (e["protocol_id"].as_u64().unwrap(), k.clone()))
        .collect();
    v.sort();
    for (i, (id, _)) in v.iter().enumerate() {
        assert_eq!(*id as usize, i, "{name}: ids not dense");
    }
    v.into_iter().map(|(_, k)| k).collect()
}

/// A name list as one text blob and end offsets: plain read-only data (no pointers, so no
/// load-time relocations: untouched pages stay unresident and shared between processes).
fn text_table(out: &mut String, konst: &str, doc: &str, names: &[&str]) {
    let mut text = String::new();
    let mut ends = Vec::new();
    for n in names {
        text.push_str(n);
        ends.push(text.len());
    }
    let _ = writeln!(
        out,
        "/// {doc} (text of [`{konst}_ENDS`]).\npub(crate) const {konst}_TEXT: &str = {text:?};\n\
         /// End offset of each name in [`{konst}_TEXT`].\npub(crate) static {konst}_ENDS: [u32; {}] = {ends:?};\n",
        ends.len()
    );
}

/// Interns strings into one blob: `(offset, len)` spans.
#[derive(Default)]
struct Blob {
    text: String,
    seen: std::collections::HashMap<String, (usize, usize)>,
}

impl Blob {
    fn span(&mut self, s: &str) -> String {
        let (o, l) = *self.seen.entry(s.to_string()).or_insert_with(|| {
            let o = self.text.len();
            self.text.push_str(s);
            (o, s.len())
        });
        format!("({o}, {l})")
    }
}

fn strip(s: &str) -> &str {
    s.strip_prefix("minecraft:").unwrap_or(s)
}

fn main() {
    let dir = std::env::args().nth(1).expect("reports dir");
    let dir = Path::new(&dir);
    let reg: Value =
        serde_json::from_str(&std::fs::read_to_string(dir.join("registries.json")).unwrap())
            .unwrap();
    let items = registry(&reg, "minecraft:item");
    let comps = registry(&reg, "minecraft:data_component_type");
    let menus = registry(&reg, "minecraft:menu");
    let potions = registry(&reg, "minecraft:potion");
    // (constant, registry, part of the public API)
    let statics = [
        ("ATTRIBUTES", "minecraft:attribute", true),
        ("SOUND_EVENTS", "minecraft:sound_event", true),
        ("VILLAGER_TYPES", "minecraft:villager_type", true),
        ("MOB_EFFECTS", "minecraft:mob_effect", false),
        ("ENTITY_TYPES", "minecraft:entity_type", false),
        ("BLOCK_ENTITY_TYPES", "minecraft:block_entity_type", false),
    ];

    let mut out = String::new();
    out.push_str(
        "// @generated by `cargo run -p ghast-inventory --example gen_items_26_1` from Mojang's\n\
         // 26.1.2 data reports (registries.json and the per-item default components).\n\
         // Do not edit.\n\n",
    );
    let _ = writeln!(
        out,
        "/// Number of items (registry ids `0..ITEM_COUNT`).\npub const ITEM_COUNT: usize = {};\n",
        items.len()
    );

    // Component type ids.
    out.push_str("/// `minecraft:data_component_type` registry ids (the type id of a component on the wire).\npub mod component {\n");
    for (i, c) in comps.iter().enumerate() {
        let name = strip(c).replace('/', "_").to_uppercase();
        let _ = writeln!(out, "    /// `{c}`\n    pub const {name}: i32 = {i};");
    }
    out.push_str("}\n\n");
    let _ = writeln!(
        out,
        "/// Component type names by id.\npub static COMPONENT_NAMES: [&str; {}] = [",
        comps.len()
    );
    for c in &comps {
        let _ = writeln!(out, "    {:?},", strip(c));
    }
    out.push_str("];\n\n");
    let names: Vec<&str> = comps.iter().map(|c| strip(c)).collect();
    text_table(
        &mut out,
        "COMPONENT_NAMES",
        "Component type names by id",
        &names,
    );

    let _ = writeln!(
        out,
        "/// `minecraft:menu` registry names by id (the `open_screen` window type).\npub static MENUS: [&str; {}] = [",
        menus.len()
    );
    for m in &menus {
        let _ = writeln!(out, "    {:?},", strip(m));
    }
    out.push_str("];\n\n");
    let names: Vec<&str> = menus.iter().map(|c| strip(c)).collect();
    text_table(&mut out, "MENUS", "`minecraft:menu` registry names", &names);
    let _ = writeln!(
        out,
        "/// `minecraft:potion` registry names by id.\npub static POTIONS: [&str; {}] = [",
        potions.len()
    );
    for p in &potions {
        let _ = writeln!(out, "    {:?},", strip(p));
    }
    out.push_str("];\n\n");
    let names: Vec<&str> = potions.iter().map(|c| strip(c)).collect();
    text_table(
        &mut out,
        "POTIONS",
        "`minecraft:potion` registry names",
        &names,
    );

    for (konst, name, public) in statics {
        let names = registry(&reg, name);
        if public {
            // kept for the public API; ghast itself reads the text table below
            let _ = writeln!(
                out,
                "/// `{name}` registry names by id.\npub static {konst}: [&str; {}] = [",
                names.len()
            );
            for n in &names {
                let _ = writeln!(out, "    {:?},", strip(n));
            }
            out.push_str("];\n\n");
        }
        let names: Vec<&str> = names.iter().map(|c| strip(c)).collect();
        text_table(&mut out, konst, &format!("`{name}` registry names"), &names);
    }

    let _ = writeln!(
        out,
        "/// Default components of every item, by registry id (strings as spans of [`ITEM_TEXT`]).\n\
         pub(crate) static ITEM_ROWS: [Row; {}] = [",
        items.len()
    );
    let mut blob = Blob::default();
    for it in &items {
        let name = strip(it);
        let path = dir
            .join("minecraft/components/item")
            .join(format!("{name}.json"));
        let v: Value = serde_json::from_str(&std::fs::read_to_string(&path).unwrap()).unwrap();
        let c = &v["components"];
        let max_stack = c["minecraft:max_stack_size"].as_u64().unwrap_or(1);
        let max_damage = c["minecraft:max_damage"].as_u64().unwrap_or(0);
        let damage = c.get("minecraft:damage").is_some();
        let unbreakable = c.get("minecraft:unbreakable").is_some();
        let glider = c.get("minecraft:glider").is_some();
        let equip = match c["minecraft:equippable"]
            .get("slot")
            .and_then(Value::as_str)
        {
            None => "None",
            Some("head") => "Head",
            Some("chest") => "Chest",
            Some("legs") => "Legs",
            Some("feet") => "Feet",
            Some("offhand") => "Offhand",
            Some("mainhand") => "MainHand",
            Some("body") => "Body",
            Some("saddle") => "Saddle",
            Some(o) => panic!("slot {o}"),
        };
        let restricted = c["minecraft:equippable"].get("allowed_entities").is_some();
        let bundle = c.get("minecraft:bundle_contents").is_some();
        let rarity = match c["minecraft:rarity"].as_str().unwrap_or("common") {
            "common" => 0,
            "uncommon" => 1,
            "rare" => 2,
            "epic" => 3,
            o => panic!("rarity {o}"),
        };
        // use_effects (every item has one), consumable, food, blocks_attacks, kinetic_weapon
        let ue = &c["minecraft:use_effects"];
        let use_sprint = ue["can_sprint"].as_bool().unwrap_or(false);
        let use_vibrations = ue["interact_vibrations"].as_bool().unwrap_or(true);
        let use_speed = ue["speed_multiplier"].as_f64().unwrap_or(0.2) as f32;
        let consume = match c.get("minecraft:consumable") {
            None => "None".to_string(),
            Some(co) => {
                let secs = co["consume_seconds"].as_f64().unwrap_or(1.6) as f32;
                let anim = match co["animation"].as_str().unwrap_or("eat") {
                    "none" => 0,
                    "eat" => 1,
                    "drink" => 2,
                    "block" => 3,
                    "bow" => 4,
                    "trident" => 5,
                    "crossbow" => 6,
                    "spyglass" => 7,
                    "toot_horn" => 8,
                    "brush" => 9,
                    "bundle" => 10,
                    "spear" => 11,
                    o => panic!("animation {o}"),
                };
                format!("Some(({:#x}, {anim}))", secs.to_bits())
            }
        };
        let food = match c.get("minecraft:food") {
            None => "None".to_string(),
            Some(f) => format!(
                "Some(({}, {:#x}, {}))",
                f["nutrition"].as_i64().unwrap(),
                (f["saturation"].as_f64().unwrap() as f32).to_bits(),
                f["can_always_eat"].as_bool().unwrap_or(false)
            ),
        };
        let repairable = c["minecraft:repairable"]["items"]
            .as_str()
            .unwrap_or("")
            .to_string();
        let patterns = c["minecraft:provides_banner_patterns"]
            .as_str()
            .unwrap_or("")
            .to_string();
        const DYES: [&str; 16] = [
            "white",
            "orange",
            "magenta",
            "light_blue",
            "yellow",
            "lime",
            "pink",
            "gray",
            "light_gray",
            "cyan",
            "purple",
            "blue",
            "brown",
            "green",
            "red",
            "black",
        ];
        let dye = c["minecraft:dye"].as_str().map_or(255, |d| {
            DYES.iter().position(|x| *x == d).expect("dye") as u8
        });
        let allowed = match &c["minecraft:equippable"]["allowed_entities"] {
            Value::String(t) => t.clone(),
            Value::Array(a) => a
                .iter()
                .map(|x| x.as_str().unwrap())
                .collect::<Vec<_>>()
                .join(","),
            _ => String::new(),
        };
        let blocks = c.get("minecraft:blocks_attacks").is_some();
        let kinetic = c.get("minecraft:kinetic_weapon").is_some();
        let _ = writeln!(
            out,
            "    Row {{ name_s: {}, max_stack_size: {max_stack}, max_damage: {max_damage}, damage: {damage}, unbreakable: {unbreakable}, equip: Equip::{equip}, equip_restricted: {restricted}, bundle: {bundle}, rarity: {rarity}, use_effects: ({use_sprint}, {use_vibrations}, {:#x}), consumable: {consume}, food: {food}, blocks_attacks: {blocks}, kinetic_weapon: {kinetic}, repairable_s: {}, patterns_s: {}, dye: {dye}, allowed_s: {}, glider: {glider} }},",
            blob.span(name),
            use_speed.to_bits(),
            blob.span(&repairable),
            blob.span(&patterns),
            blob.span(&allowed),
        );
    }
    out.push_str("];\n\n");
    let _ = writeln!(
        out,
        "/// The strings of [`ITEM_ROWS`] (item names, repair items, banner patterns, allowed entities).\n\
         pub(crate) const ITEM_TEXT: &str = {:?};",
        blob.text
    );
    let target = Path::new(env!("CARGO_MANIFEST_DIR")).join("src/generated/items_26_1.rs");
    std::fs::create_dir_all(target.parent().unwrap()).unwrap();
    std::fs::write(&target, out).unwrap();
    println!(
        "{} items, {} component types -> {}",
        items.len(),
        comps.len(),
        target.display()
    );
}
