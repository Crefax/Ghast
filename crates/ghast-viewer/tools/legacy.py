#!/usr/bin/env python3
"""Generates src/legacy_table.rs from minecraft-data's pc/common/legacy.json (MIT): the
pre-flattening `id:meta` of every block state and item with its 1.13+ name. The 26.1 viewer
maps 26.1 blocks and items onto the 1.8 ones the page draws with it.

    python3 -I crates/ghast-viewer/tools/legacy.py .cache/minecraft-data/3.119.0/package/minecraft-data
"""
import json
import pathlib
import sys

root = pathlib.Path(sys.argv[1])
data = json.loads((root / "data/pc/common/legacy.json").read_text())
out = pathlib.Path(__file__).resolve().parent.parent / "src/legacy_table.rs"


def entries(table):
    rows = []
    for k, v in table.items():
        i, m = (int(x) for x in k.split(":"))
        rows.append((i, m, v.removeprefix("minecraft:")))
    rows.sort()
    return rows


lines = [
    "//! Generated by `tools/legacy.py` from minecraft-data's `pc/common/legacy.json` (MIT);",
    "//! do not edit. Pre-flattening `(id, meta)` and the flattened name of every block state",
    "//! and item.",
    "",
    "/// `(id, meta, \"name[properties]\")` of the block states.",
    "pub(crate) static BLOCKS: &[(u16, u8, &str)] = &[",
]
lines += [f"    ({i}, {m}, {json.dumps(n)})," for i, m, n in entries(data["blocks"])]
lines += ["];", "", "/// `(id, meta, \"name\")` of the items.", "pub(crate) static ITEMS: &[(u16, u16, &str)] = &["]
lines += [f"    ({i}, {m}, {json.dumps(n)})," for i, m, n in entries(data["items"])]
lines += ["];", ""]
out.write_text("\n".join(lines))
print(f"wrote {out}")
